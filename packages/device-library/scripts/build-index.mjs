// Regenerates src/generated.ts from templates/<vendor>/<model>.json. Run with `pnpm --filter @linewise/device-library index`.
import { readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tdir = join(root, 'templates');
const files = readdirSync(tdir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .flatMap((d) =>
    readdirSync(join(tdir, d.name))
      .filter((f) => f.endsWith('.json'))
      .map((f) => `${d.name}/${f}`),
  )
  .sort();
const lines = [
  '// SPDX-License-Identifier: Apache-2.0',
  '// Generated by scripts/build-index.mjs — do not edit by hand.',
  ...files.map((f, i) => `import t${i} from '../templates/${f}' with { type: 'json' };`),
  '',
  `export const RAW_TEMPLATES: unknown[] = [${files.map((_, i) => `t${i}`).join(', ')}];`,
  '',
];
writeFileSync(join(root, 'src/generated.ts'), lines.join('\n'));
console.log(`Indexed ${files.length} templates`);
