/**
 * Writes THIRD_PARTY_NOTICES.md (OSS-03) for everything that ships in the app: production npm
 * packages, Rust crates and the bundled fonts. A copy goes to apps/desktop/public so the About
 * dialog can show it offline. Identical license texts are printed once and referenced by id.
 * The files are build outputs (git-ignored); `pnpm --filter @linewise/desktop build` regenerates them.
 * `--no-cargo` skips Rust crates; this also happens automatically, with a warning, when cargo
 * is not installed (web-only development) or LINEWISE_NOTICES_NO_CARGO=1 (browser E2E builds).
 * Desktop CI and release builds always include them.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, cargoPackages, licenseText, npmPackages } from './licenses.mjs';

function hasCargo() {
  try {
    execFileSync('cargo', ['--version'], { stdio: 'ignore' });
    return true;
  } catch {
    console.warn('third-party-notices: cargo not found, Rust crates are not listed.');
    return false;
  }
}
const skipCargo =
  process.argv.includes('--no-cargo') || process.env.LINEWISE_NOTICES_NO_CARGO === '1' || !hasCargo();
const FENCE = '```';

const fonts = [
  { name: 'Sora', version: '', license: 'OFL-1.1', file: 'packages/brand/fonts/Sora-OFL.txt' },
  {
    name: 'IBM Plex Mono',
    version: '',
    license: 'OFL-1.1',
    file: 'packages/brand/fonts/IBMPlexMono-OFL.txt',
  },
];

// Collapse identical name@version entries (pnpm lists a package once per install path).
function unique(list) {
  const seen = new Set();
  return list.filter((p) => {
    const k = `${p.name}@${p.version}`;
    if (seen.has(k)) return false;
    seen.add(k);
    return true;
  });
}

const npm = unique(npmPackages({ prod: true }));
const crates = skipCargo ? [] : unique(cargoPackages());

// Group identical license texts so each one is printed once.
const texts = new Map();
const textIds = new Map();
function register(p, raw) {
  const text = raw.replace(/\r\n/g, '\n').trim();
  if (!text) return;
  if (!texts.has(text)) texts.set(text, { id: `L${texts.size + 1}`, users: [] });
  const entry = texts.get(text);
  entry.users.push(`${p.name}${p.version ? ` ${p.version}` : ''}`);
  textIds.set(p, entry.id);
}
for (const f of fonts) register(f, readFileSync(join(ROOT, f.file), 'utf8'));
for (const p of [...npm, ...crates]) register(p, licenseText(p.path));

function line(p) {
  const parts = [`${p.name}${p.version ? ` ${p.version}` : ''}`, p.license || 'UNKNOWN'];
  if (p.homepage) parts.push(p.homepage);
  if (textIds.has(p)) parts.push(`text [${textIds.get(p)}]`);
  return `- ${parts.join(' — ')}`;
}

let out = `# Third-party notices

LineWise is licensed under Apache-2.0. It includes the third-party software listed below, each under its own license.
This file is generated by \`pnpm notices\`; do not edit it by hand.

## Fonts

${fonts.map(line).join('\n')}

## npm packages (${npm.length})

${npm.map(line).join('\n')}
`;
if (!skipCargo) out += `\n## Rust crates (${crates.length})\n\n${crates.map(line).join('\n')}\n`;
out += '\n## License texts\n';
for (const [text, { id, users }] of texts) {
  out += `\n### [${id}]\n\nUsed by: ${users.join(', ')}\n\n${FENCE}text\n${text.replaceAll(FENCE, "'''")}\n${FENCE}\n`;
}

const targets = [
  join(ROOT, 'THIRD_PARTY_NOTICES.md'),
  join(ROOT, 'apps/desktop/public/THIRD_PARTY_NOTICES.md'),
];
for (const t of targets) writeFileSync(t, out);
console.log(
  `Wrote THIRD_PARTY_NOTICES.md (${npm.length} npm packages, ${crates.length} crates, ${fonts.length} fonts, ${texts.size} distinct license texts).`,
);
